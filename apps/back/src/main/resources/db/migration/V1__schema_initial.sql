-- Schéma de départ : celui que Hibernate créait avec `ddl-auto` au 2026-10-24,
-- relevé sur PostgreSQL 17 puis réécrit à la main.
--
-- Une base qui existait avant Flyway (préproduction) ne rejoue pas ce script :
-- `baseline-on-migrate` l'inscrit d'office en version 1. Les noms de contraintes
-- sont donc ceux que PostgreSQL et Hibernate y ont posés, pour qu'une migration
-- future puisse les viser de la même façon partout.
--
-- SQL commun à PostgreSQL et à H2 (mode PostgreSQL) : les tests jouent ce même
-- script.

CREATE TABLE campaigns (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(255) NOT NULL,
    description TEXT         NOT NULL,
    start_date  TIMESTAMP(6),
    end_date    TIMESTAMP(6),
    status      VARCHAR(255) NOT NULL,
    archived    BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT campaigns_pkey PRIMARY KEY (id),
    CONSTRAINT campaigns_status_check
        CHECK (status IN ('DRAFT', 'ACTIVE', 'COMPLETED', 'SCHEDULED', 'CANCELED'))
);

CREATE TABLE publications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    content     TEXT         NOT NULL,
    status      VARCHAR(255) NOT NULL,
    campaign_id BIGINT,
    archived    BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    CONSTRAINT publications_pkey PRIMARY KEY (id),
    CONSTRAINT publications_status_check CHECK (status IN ('DRAFT', 'VERIFIED')),
    CONSTRAINT fkp274j4kwu2858eymfftfq1tvb FOREIGN KEY (campaign_id) REFERENCES campaigns (id)
);

CREATE TABLE publication_occurrences (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    publication_id BIGINT       NOT NULL,
    scheduled_at   TIMESTAMP(6) NOT NULL,
    status         VARCHAR(255) NOT NULL,
    pinned         BOOLEAN      DEFAULT FALSE NOT NULL,
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    CONSTRAINT publication_occurrences_pkey PRIMARY KEY (id),
    CONSTRAINT publication_occurrences_status_check CHECK (status IN ('SCHEDULED', 'PUBLISHED', 'FAILED')),
    CONSTRAINT fkka2yi9u7r7h8coh0g6v8g3c1l FOREIGN KEY (publication_id) REFERENCES publications (id)
);

CREATE TABLE publication_deliveries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    occurrence_id BIGINT       NOT NULL,
    channel       VARCHAR(255) NOT NULL,
    status        VARCHAR(255) NOT NULL,
    published_at  TIMESTAMP(6),
    external_id   VARCHAR(255),
    error_message TEXT,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6),
    CONSTRAINT publication_deliveries_pkey PRIMARY KEY (id),
    CONSTRAINT publication_deliveries_channel_check CHECK (channel IN ('FACEBOOK', 'INTRAMUROS')),
    CONSTRAINT publication_deliveries_status_check
        CHECK (status IN ('PENDING', 'IN_PROGRESS', 'PUBLISHED', 'FAILED')),
    CONSTRAINT fkbwwikv9d857rfdrtc04l3fcfx FOREIGN KEY (occurrence_id) REFERENCES publication_occurrences (id)
);

CREATE TABLE medias (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title             VARCHAR(255),
    original_filename VARCHAR(255) NOT NULL,
    storage_key       VARCHAR(255) NOT NULL,
    file_type         VARCHAR(255) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    checksum          VARCHAR(64)  NOT NULL,
    width             INTEGER,
    height            INTEGER,
    alt_text          TEXT,
    archived          BOOLEAN      NOT NULL,
    created_at        TIMESTAMP(6),
    updated_at        TIMESTAMP(6),
    CONSTRAINT medias_pkey PRIMARY KEY (id),
    CONSTRAINT medias_storage_key_key UNIQUE (storage_key),
    CONSTRAINT medias_file_type_check CHECK (file_type IN ('JPEG', 'PNG', 'WEBP', 'PDF'))
);

CREATE TABLE publication_medias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    publication_id BIGINT  NOT NULL,
    media_id       BIGINT  NOT NULL,
    position       INTEGER NOT NULL,
    CONSTRAINT publication_medias_pkey PRIMARY KEY (id),
    CONSTRAINT publication_medias_publication_id_media_id_key UNIQUE (publication_id, media_id),
    CONSTRAINT fk5909k7cxb9yviq7bbyxhq6h02 FOREIGN KEY (publication_id) REFERENCES publications (id),
    CONSTRAINT fkjm84i2o8aurluy8o89pw53ua1 FOREIGN KEY (media_id) REFERENCES medias (id)
);

CREATE TABLE facebook_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    access_token VARCHAR(512) NOT NULL,
    token_type   VARCHAR(255) NOT NULL,
    expires_at   TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT facebook_tokens_pkey PRIMARY KEY (id)
);

CREATE TABLE channel_suspensions (
    channel      VARCHAR(255) NOT NULL,
    reason       TEXT         NOT NULL,
    suspended_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT channel_suspensions_pkey PRIMARY KEY (channel),
    CONSTRAINT channel_suspensions_channel_check CHECK (channel IN ('FACEBOOK', 'INTRAMUROS'))
);
