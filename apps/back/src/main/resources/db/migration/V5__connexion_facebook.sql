-- Connexion de la Page Facebook depuis l'interface (flux OAuth de Facebook Login).
--
-- Tables nouvelles, à côté de `facebook_tokens` que le mécanisme historique
-- (bootstrap) continue d'utiliser : FACEBOOK_TOKEN_SOURCE=legacy y revient sans
-- rien migrer. Une version du code antérieure à celle-ci ignore ces tables.

-- La connexion en vigueur : une ligne au plus, remplacée à chaque reconnexion.
CREATE TABLE facebook_connections (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    page_id                VARCHAR(64)   NOT NULL,
    page_name              VARCHAR(255)  NOT NULL,
    access_token           TEXT          NOT NULL,
    scopes                 VARCHAR(1024) NOT NULL,
    connected_by           VARCHAR(32)   NOT NULL,
    connected_at           TIMESTAMP(6)  NOT NULL,
    -- Vides quand Facebook n'annonce pas d'échéance (jeton de Page permanent).
    expires_at             TIMESTAMP(6),
    data_access_expires_at TIMESTAMP(6),
    last_checked_at        TIMESTAMP(6),
    last_check_result      VARCHAR(16),
    last_check_message     VARCHAR(512),
    CONSTRAINT facebook_connections_pkey PRIMARY KEY (id),
    CONSTRAINT facebook_connections_last_check_result_check
        CHECK (last_check_result IN ('VALID', 'INVALID', 'UNKNOWN'))
);

-- Demandes de connexion en cours : le `state` OAuth, à usage unique. Le retour
-- de Facebook arrive sans cookie de session (SameSite=strict) ; c'est cette
-- ligne qui dit quel compte a lancé la connexion.
CREATE TABLE facebook_oauth_states (
    state      VARCHAR(64)  NOT NULL,
    username   VARCHAR(32)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT facebook_oauth_states_pkey PRIMARY KEY (state)
);

