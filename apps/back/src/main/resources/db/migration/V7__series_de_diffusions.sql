-- Programmation par fréquence : une série porte la règle de répétition (RRULE,
-- RFC 5545) d'une publication ; un job quotidien en crée les diffusions à
-- l'avance, sur un horizon borné.
--
-- `generated_through` est le curseur de génération : les dates jusqu'à ce jour
-- ont déjà été traitées. Une diffusion de la série déplacée ou annulée à la main
-- n'est donc jamais recréée.
CREATE TABLE occurrence_series (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    publication_id    BIGINT       NOT NULL,
    rule              VARCHAR(255) NOT NULL,
    start_date        DATE         NOT NULL,
    publish_time      TIME,
    status            VARCHAR(16)  NOT NULL,
    generated_through DATE,
    stop_reason       VARCHAR(255),
    created_at        TIMESTAMP(6),
    created_by        VARCHAR(32),
    updated_at        TIMESTAMP(6),
    CONSTRAINT occurrence_series_pkey PRIMARY KEY (id),
    CONSTRAINT occurrence_series_status_check CHECK (status IN ('ACTIVE', 'COMPLETED', 'STOPPED')),
    CONSTRAINT occurrence_series_publication_fk FOREIGN KEY (publication_id) REFERENCES publications (id)
);

CREATE TABLE occurrence_series_channels (
    series_id BIGINT      NOT NULL,
    channel   VARCHAR(32) NOT NULL,
    CONSTRAINT occurrence_series_channels_pkey PRIMARY KEY (series_id, channel),
    CONSTRAINT occurrence_series_channels_channel_check CHECK (channel IN ('FACEBOOK', 'INTRAMUROS')),
    CONSTRAINT occurrence_series_channels_series_fk FOREIGN KEY (series_id) REFERENCES occurrence_series (id)
        ON DELETE CASCADE
);

-- Chaque diffusion générée garde le lien vers sa série et sa date d'origine.
ALTER TABLE publication_occurrences ADD COLUMN series_id BIGINT;
ALTER TABLE publication_occurrences ADD COLUMN series_date DATE;
ALTER TABLE publication_occurrences ADD CONSTRAINT publication_occurrences_series_fk
    FOREIGN KEY (series_id) REFERENCES occurrence_series (id);

-- Création et arrêt d'une série passent au journal.
ALTER TABLE security_events DROP CONSTRAINT security_events_type_check;
ALTER TABLE security_events ADD CONSTRAINT security_events_type_check CHECK (type IN (
    'LOGIN_SUCCEEDED', 'LOGIN_FAILED', 'ACCOUNT_LOCKED', 'PASSWORD_CHANGED',
    'ACCOUNT_CREATED', 'PERMISSIONS_CHANGED', 'ACCOUNT_DISABLED', 'PASSWORD_RESET',
    'PUBLICATION_DELETED', 'OCCURRENCE_RESCHEDULED', 'OCCURRENCE_RETRIED', 'OCCURRENCE_CANCELLED',
    'CHANNEL_SUSPENDED', 'CHANNEL_RESUMED', 'FACEBOOK_CONNECTED',
    'SERIES_CREATED', 'SERIES_STOPPED'
));
