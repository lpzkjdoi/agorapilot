-- Journal de sécurité : connexions, verrouillages et actions d'administration
-- des comptes. Les comptes sont désignés par leur pseudo, recopié : une ligne se
-- lit seule, et un échec de connexion peut viser un pseudo qui n'existe pas.

CREATE TABLE security_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    occurred_at     TIMESTAMP(6) NOT NULL,
    type            VARCHAR(32)  NOT NULL,
    actor_username  VARCHAR(64),
    target_username VARCHAR(64),
    details         VARCHAR(512),
    CONSTRAINT security_events_pkey PRIMARY KEY (id),
    CONSTRAINT security_events_type_check CHECK (type IN (
        'LOGIN_SUCCEEDED', 'LOGIN_FAILED', 'ACCOUNT_LOCKED', 'PASSWORD_CHANGED',
        'ACCOUNT_CREATED', 'PERMISSIONS_CHANGED', 'ACCOUNT_DISABLED', 'PASSWORD_RESET'
    ))
);

CREATE INDEX security_events_occurred_at_idx ON security_events (occurred_at);
