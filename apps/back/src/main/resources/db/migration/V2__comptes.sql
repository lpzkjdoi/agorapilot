-- Comptes applicatifs : une personne = un compte (cf. docs/proposals/2026-10-24-comptes-et-droits.md).
-- Le pseudo est stocké en minuscules : l'unicité est donc insensible à la casse.

CREATE TABLE user_accounts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username            VARCHAR(32)  NOT NULL,
    password_hash       VARCHAR(100) NOT NULL,
    status              VARCHAR(32)  NOT NULL,
    failed_attempts     INTEGER      DEFAULT 0 NOT NULL,
    locked_until        TIMESTAMP(6),
    last_login_at       TIMESTAMP(6),
    password_changed_at TIMESTAMP(6) NOT NULL,
    created_at          TIMESTAMP(6),
    updated_at          TIMESTAMP(6),
    CONSTRAINT user_accounts_pkey PRIMARY KEY (id),
    CONSTRAINT user_accounts_username_key UNIQUE (username),
    CONSTRAINT user_accounts_status_check CHECK (status IN ('PENDING_PASSWORD', 'ACTIVE', 'DISABLED'))
);

-- Un droit par ligne : aucun droit n'est implicite.
CREATE TABLE user_permissions (
    user_id    BIGINT      NOT NULL,
    permission VARCHAR(64) NOT NULL,
    CONSTRAINT user_permissions_pkey PRIMARY KEY (user_id, permission),
    CONSTRAINT user_permissions_user_fkey FOREIGN KEY (user_id) REFERENCES user_accounts (id)
);
